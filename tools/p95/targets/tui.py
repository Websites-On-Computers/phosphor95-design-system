"""TUI outputs (generated into the source tree, committed, mirrored to dist/tui):

  packages/tui/terminal-themes/<format>/…   colour schemes for 8 terminals/tools x 4 themes
  packages/tui/p95-style/src/palette.rs     every semantic/component colour per theme, with its
                                            truecolor RGB, nearest xterm-256 index, and nearest
                                            index in the theme's own ANSI-16 set

xterm-256 matching uses OKLab distance over indices 16-255 (0-15 are user-defined).
ANSI-16 matching uses the theme's own ANSI set, which is what a user has once our scheme is installed.
"""
