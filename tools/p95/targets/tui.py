# ------------------------------------------------------------------- palette.rs
def field(path: str) -> str:
    if path.startswith("color.phosphor."):
        return "phosphor_" + path.rsplit(".", 1)[1]
    return re.sub(r"[^a-z0-9]+", "_", path.lower()).strip("_")


def rust_palette(ctx) -> str:
    default = ctx.default
    paths = sorted(p for p, t in default.items() if t.type == "color" and t.value.get("alpha", 1) == 1
                   and (not p.startswith("color.") or p.startswith("color.phosphor.")))
    durations = {p: t.value for p, t in default.items() if t.type == "duration"}
    out = [
        "// GENERATED by tools/build.py (target: tui) from tokens/. Do not edit.",
        "//! Every semantic and component colour of every theme, precomputed for each colour depth.",
        "#![allow(clippy::all)]",
        "",
        "use crate::Swatch;",
        "",
        "/// All theme colours. Field names are token paths with `.`/`-` → `_` (e.g. `text.secondary` →",
        "/// `text_secondary`, `color.phosphor.10` → `phosphor_10`).",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub struct Palette {",
        "    /// Theme id: green, amber, white, hc.",
        "    pub name: &'static str,",
    ]
    out += [f"    /// `{p}`\n    pub {field(p)}: Swatch," for p in paths]
    out += ["}", ""]
    for theme, toks in ctx.themes.items():
        ansi_rgbs = [colour.dtcg_to_rgba(toks[f"ansi.{n}"].value)[:3] for n in ANSI]
        out.append(f"/// Phosphor95 {THEME_TITLE[theme]}.")
        out.append(f"pub const {theme.upper()}: Palette = Palette {{")
        out.append(f'    name: "{theme}",')
        for p in paths:
            rgb = colour.dtcg_to_rgba(toks[p].value)[:3]
            idx = ANSI.index(p.split(".", 1)[1]) if p.startswith("ansi.") else nearest_ansi(rgb, ansi_rgbs)
            out.append(f"    {field(p)}: Swatch::new(0x{rgb[0]:02x}, 0x{rgb[1]:02x}, 0x{rgb[2]:02x}, {nearest_256(rgb)}, {idx}),")
        out.append("};")
        out.append("")
    out.append(f"/// All themes, default first.\npub const THEMES: [&Palette; {len(ctx.themes)}] = [" +
               ", ".join(f"&{t.upper()}" for t in ctx.themes) + "];")
    out += ["", "/// Motion durations in milliseconds (`duration.*`).", "pub mod duration {"]
    for p, v in sorted(durations.items()):
        msv = v["value"] if v["unit"] == "ms" else v["value"] * 1000
        out.append(f"    /// `{p}`\n    pub const {p.split('.', 1)[1].upper().replace('-', '_')}: u64 = {int(msv)};")
    out.append("}")
    return "\n".join(out) + "\n"


# ------------------------------------------------------------------ operator.rs
ROLES = ["hair", "shade-1", "shade-2", "mid", "skin", "light"]


def operator_grid() -> list[list[int]]:
    """Parse brand/logo/operator.svg (1px runs per role) into a 48x48 grid of role indices (0 = empty)."""
    svg = (ROOT / "brand/logo/operator.svg").read_text(encoding="utf-8")
    grid = [[0] * 48 for _ in range(48)]
    for role, d in re.findall(r'fill="var\(--p95-operator-([a-z0-9-]+),[^"]*\)" d="([^"]+)"', svg):
        for x, y, n in re.findall(r"M(\d+) (\d+)h(\d+)v1h-\d+z", d):
            for i in range(int(n)):
                grid[int(y)][int(x) + i] = ROLES.index(role) + 1
    assert any(any(r) for r in grid), "operator.svg parse failed"
    return grid


def rust_operator() -> str:
    g = operator_grid()
    rows = ",\n".join("    b\"" + "".join(str(v) for v in row) + "\"" for row in g)
    return ("// GENERATED by tools/build.py (target: tui) from brand/logo/operator.svg. Do not edit.\n"
            "//! The Operator (the lock-screen avatar) as a 48x48 grid of colour roles, for terminal rendering.\n"
            "//! Digits: 0 empty, 1 hair, 2 shade-1, 3 shade-2, 4 mid, 5 skin, 6 light.\n\n"
            "/// 48 rows of 48 ASCII digits (role per pixel).\n"
            f"pub const OPERATOR_48: [&[u8; 48]; 48] = [\n{rows},\n];\n")


# ---------------------------------------------------------------------- build
def build(ctx, out: Path) -> list[Path]:
    themes_dir = TUI / "terminal-themes"
    for d in list(FORMATS) + ["base16"]:
        shutil.rmtree(themes_dir / d, ignore_errors=True)
    written = []
    for theme, toks in ctx.themes.items():
        s = scheme(toks)
        title = THEME_TITLE[theme]
        for fmt, (ext, fn) in FORMATS.items():
            f = themes_dir / fmt / f"phosphor95-{theme}{ext}"
            f.parent.mkdir(parents=True, exist_ok=True)
            f.write_text(fn(title, s), encoding="utf-8")
            written.append(f)
        f = themes_dir / "base16" / f"phosphor95-{theme}.yaml"
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(base16(title, toks, s), encoding="utf-8")
        written.append(f)
    (themes_dir / "phosphor95.dircolors").write_text(DIRCOLORS, encoding="utf-8")
    written.append(themes_dir / "phosphor95.dircolors")

    rs = TUI / "p95-style/src/palette.rs"
    rs.parent.mkdir(parents=True, exist_ok=True)
    rs.write_text(rust_palette(ctx), encoding="utf-8")
    written.append(rs)

    op = TUI / "p95-style/src/operator.rs"
    op.write_text(rust_operator(), encoding="utf-8")
    written.append(op)

    shutil.copytree(themes_dir, out / "terminal-themes", ignore=shutil.ignore_patterns("README.md"))
    return written
