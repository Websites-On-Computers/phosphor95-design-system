# ----------------------------------------------------------------- colour math
def hexof(tok) -> str:
    return colour.rgb_to_hex(colour.dtcg_to_rgba(tok.value)[:3])


def _oklab(rgb):
    L, C, h = colour.rgb_to_oklch(rgb)
    return L, C * math.cos(math.radians(h)), C * math.sin(math.radians(h))


def _dist(a, b):
    return sum((x - y) ** 2 for x, y in zip(_oklab(a), _oklab(b)))


def xterm256() -> list[tuple[int, int, int]]:
    """RGB for indices 16-255 (list index 0 = xterm 16)."""
    levels = [0, 95, 135, 175, 215, 255]
    cube = [(levels[r], levels[g], levels[b]) for r in range(6) for g in range(6) for b in range(6)]
    grey = [(8 + 10 * i,) * 3 for i in range(24)]
    return cube + grey


XTERM = xterm256()


def nearest_256(rgb) -> int:
    return 16 + min(range(len(XTERM)), key=lambda i: _dist(rgb, XTERM[i]))


def nearest_ansi(rgb, ansi_rgbs) -> int:
    return min(range(16), key=lambda i: _dist(rgb, ansi_rgbs[i]))


# ------------------------------------------------------------------- schemes
def scheme(toks) -> dict:
    h = lambda p: hexof(toks[p])  # noqa: E731
    return {
        "bg": h("surface.base"), "fg": h("text.primary"),
        "cursor": h("text.hot"), "cursor_text": h("surface.base"),
        "sel_bg": h("select.bg"), "sel_fg": h("select.fg"),
        "border": h("border.strong"), "url": h("text.link"),
        "ansi": [h(f"ansi.{n}") for n in ANSI],
    }


def ghostty(name, s):
    lines = [f"# Phosphor95 {name}. Generated by tools/build.py.", f"background = {s['bg']}", f"foreground = {s['fg']}",
             f"cursor-color = {s['cursor']}", f"cursor-text = {s['cursor_text']}",
             f"selection-background = {s['sel_bg']}", f"selection-foreground = {s['sel_fg']}"]
    lines += [f"palette = {i}={c}" for i, c in enumerate(s["ansi"])]
    return "\n".join(lines) + "\n"


def kitty(name, s):
    lines = [f"# Phosphor95 {name}. Generated by tools/build.py.", f"foreground {s['fg']}", f"background {s['bg']}",
             f"selection_foreground {s['sel_fg']}", f"selection_background {s['sel_bg']}", f"cursor {s['cursor']}",
             f"cursor_text_color {s['cursor_text']}", f"url_color {s['url']}", f"active_border_color {s['border']}",
             f"inactive_border_color {s['ansi'][8]}", f"active_tab_foreground {s['sel_fg']}",
             f"active_tab_background {s['sel_bg']}", f"inactive_tab_foreground {s['fg']}", f"inactive_tab_background {s['bg']}"]
    lines += [f"color{i} {c}" for i, c in enumerate(s["ansi"])]
    return "\n".join(lines) + "\n"


def alacritty(name, s):
    a = s["ansi"]
    names = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"]
    out = [f"# Phosphor95 {name}. Generated by tools/build.py.", "[colors.primary]", f'background = "{s["bg"]}"',
           f'foreground = "{s["fg"]}"', "", "[colors.cursor]", f'cursor = "{s["cursor"]}"', f'text = "{s["cursor_text"]}"',
           "", "[colors.selection]", f'background = "{s["sel_bg"]}"', f'text = "{s["sel_fg"]}"', "", "[colors.normal]"]
    out += [f'{n} = "{a[i]}"' for i, n in enumerate(names)] + ["", "[colors.bright]"]
    out += [f'{n} = "{a[i + 8]}"' for i, n in enumerate(names)]
    return "\n".join(out) + "\n"


def wezterm(name, s):
    a = s["ansi"]
    q = lambda xs: "[" + ", ".join(f'"{x}"' for x in xs) + "]"  # noqa: E731
    return "\n".join([
        f"# Phosphor95 {name}. Generated by tools/build.py.", "[colors]", f'foreground = "{s["fg"]}"',
        f'background = "{s["bg"]}"', f'cursor_bg = "{s["cursor"]}"', f'cursor_fg = "{s["cursor_text"]}"',
        f'cursor_border = "{s["cursor"]}"', f'selection_fg = "{s["sel_fg"]}"', f'selection_bg = "{s["sel_bg"]}"',
        f'split = "{s["border"]}"', f"ansi = {q(a[:8])}", f"brights = {q(a[8:])}", "", "[metadata]",
        f'name = "Phosphor95 {name}"', 'origin_url = "https://github.com/Websites-On-Computers/phosphor95-design-system"', ""])


def foot(name, s):
    n = lambda c: c.lstrip("#")  # noqa: E731
    lines = [f"# Phosphor95 {name}. Generated by tools/build.py.", "[cursor]", f"color={n(s['cursor_text'])} {n(s['cursor'])}",
             "", "[colors]", f"foreground={n(s['fg'])}", f"background={n(s['bg'])}",
             f"selection-foreground={n(s['sel_fg'])}", f"selection-background={n(s['sel_bg'])}", f"urls={n(s['url'])}"]
    lines += [f"regular{i}={n(c)}" for i, c in enumerate(s["ansi"][:8])]
    lines += [f"bright{i}={n(c)}" for i, c in enumerate(s["ansi"][8:])]
    return "\n".join(lines) + "\n"


def windows_terminal(name, s):
    a = s["ansi"]
    keys = ["black", "red", "green", "yellow", "blue", "purple", "cyan", "white"]
    d = {"name": f"Phosphor95 {name}", "background": s["bg"], "foreground": s["fg"], "cursorColor": s["cursor"],
         "selectionBackground": s["sel_bg"]}
    for i, k in enumerate(keys):
        d[k] = a[i]
        d["bright" + k[0].upper() + k[1:]] = a[i + 8]
    return json.dumps(d, indent=2) + "\n"


def iterm(name, s):
    def entry(key, hx):
        r, g, b = (int(hx[i:i + 2], 16) / 255 for i in (1, 3, 5))
        return (f"\t<key>{key}</key>\n\t<dict>\n\t\t<key>Color Space</key>\n\t\t<string>sRGB</string>\n"
                f"\t\t<key>Red Component</key>\n\t\t<real>{r:.6f}</real>\n\t\t<key>Green Component</key>\n"
                f"\t\t<real>{g:.6f}</real>\n\t\t<key>Blue Component</key>\n\t\t<real>{b:.6f}</real>\n\t</dict>\n")
    body = "".join(entry(f"Ansi {i} Color", c) for i, c in enumerate(s["ansi"]))
    for k, c in [("Background Color", s["bg"]), ("Foreground Color", s["fg"]), ("Bold Color", s["cursor"]),
                 ("Cursor Color", s["cursor"]), ("Cursor Text Color", s["cursor_text"]),
                 ("Selection Color", s["sel_bg"]), ("Selected Text Color", s["sel_fg"]), ("Link Color", s["url"])]:
        body += entry(k, c)
    return ('<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" '
            '"http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n'
            f'<!-- Phosphor95 {name}. Generated by tools/build.py. -->\n<plist version="1.0">\n<dict>\n{body}</dict>\n</plist>\n')


def base16(name, toks, s):
    h = lambda p: hexof(toks[p]).lstrip("#")  # noqa: E731
    a = [c.lstrip("#") for c in s["ansi"]]
    pal = {"base00": h("surface.base"), "base01": h("surface.face"), "base02": h("surface.selected-subtle"),
           "base03": h("text.secondary"), "base04": h("color.phosphor.9"), "base05": h("text.primary"),
           "base06": h("color.phosphor.11"), "base07": h("text.hot"), "base08": a[1], "base09": h("status.warn.fg"),
           "base0A": a[3], "base0B": a[2], "base0C": a[6], "base0D": h("text.link"), "base0E": a[5], "base0F": a[9]}
    return "\n".join([f'scheme: "Phosphor95 {name}"', 'author: "Phosphor95 (generated by tools/build.py)"',
                      *[f'{k}: "{v}"' for k, v in pal.items()]]) + "\n"


