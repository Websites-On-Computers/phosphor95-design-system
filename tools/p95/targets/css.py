"""dist/css/tokens.css: CSS custom properties.

* `:root` carries every token for the default theme.
* Each other theme gets a `[data-theme="<name>"]` block with only the tokens that
  differ, so `data-theme` can be set on any element.
* A whole-value alias is written as `var(--p95-…)`, which keeps the token tiers visible
  in devtools.

Theme blocks re-declare every token whose *resolved* value differs from the default,
including aliases whose own text is unchanged (e.g. `text.primary` -> `{color.phosphor.10}`).
That matters because a custom property's var() is substituted on the element that declares
it. Without the re-declaration, `data-theme` on a subtree would change the ramp but not the
semantic tokens inherited from :root.
"""
from __future__ import annotations

import re
from pathlib import Path

from .. import PREFIX
from .. import color as colour


def var_name(path: str) -> str:
    parts = []
    for seg in path.split("."):
        seg = re.sub(r"(?<=[a-z0-9])([A-Z])", r"-\1", seg).lower()
        parts.append(re.sub(r"[^a-z0-9-]+", "-", seg).strip("-"))
    return f"--{PREFIX}-" + "-".join(parts)


def _family(v) -> str:
    names = [v] if isinstance(v, str) else v
    generic = {"serif", "sans-serif", "monospace", "cursive", "fantasy", "system-ui", "ui-monospace"}
    return ", ".join(n if n in generic else f'"{n}"' for n in names)


def fmt(ttype: str, v) -> str | None:
    """CSS text for a resolved value, or None when the type has no CSS form here."""
    if ttype == "color":
        return colour.to_css(v)
    if ttype in ("dimension", "duration"):
        return f"{v['value']:g}{v['unit']}"
    if ttype == "number":
        return f"{v:g}"
    if ttype == "fontWeight":
        return str(v)
    if ttype == "fontFamily":
        return _family(v)
    if ttype == "cubicBezier":
        return "cubic-bezier({})".format(", ".join(f"{n:g}" for n in v))
    if ttype == "strokeStyle":
        return v if isinstance(v, str) else None
    if ttype == "border":
        return f"{fmt('dimension', v['width'])} {v['style'] if isinstance(v['style'], str) else 'solid'} {fmt('color', v['color'])}"
    if ttype == "transition":
        return f"{fmt('duration', v['duration'])} {fmt('cubicBezier', v['timingFunction'])} {fmt('duration', v['delay'])}"
    return None  # typography / shadow: emitted by component CSS, not as one variable


def decl(tok) -> str | None:
    if tok.alias_of:
        return f"var({var_name(tok.alias_of)})"
    return fmt(tok.type, tok.value)


def build(ctx, out: Path) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)
    default = ctx.default
    lines = [
        "/* Phosphor95 design tokens. Generated by tools/build.py; do not edit. */",
        "",
        f":root, [data-theme=\"{ctx.default_theme}\"] {{",
    ]
    for p, t in sorted(default.items()):
        d = decl(t)
        if d is not None:
            lines.append(f"  {var_name(p)}: {d};")
    lines.append("}")

    for theme, toks in ctx.themes.items():
        if theme == ctx.default_theme:
            continue
        diff = []
        for p, t in sorted(toks.items()):
            base = default.get(p)
            if base is None or base.raw != t.raw or base.value != t.value:
                d = decl(t)
                if d is not None:
                    diff.append(f"  {var_name(p)}: {d};")
        lines += ["", f"[data-theme=\"{theme}\"] {{", *diff, "}"]

    f = out / "tokens.css"
    f.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return [f]
