"""foundations/contrast.generated.md: every gate check, measured, per theme.

Written into the source tree (not dist/) so the docs always show the numbers the build
actually enforces. Regenerated on every build; do not edit by hand.
"""
from __future__ import annotations

import json
from pathlib import Path

from .. import ROOT, TOKENS
from .. import color as colour


def _hex(t):
    return colour.rgb_to_hex(colour.dtcg_to_rgba(t.value)[:3])


def build(ctx, out: Path) -> list[Path]:
    checks = json.loads((TOKENS / "checks.json").read_text(encoding="utf-8"))["contrast"]
    themes = list(ctx.themes)
    lines = [
        "# Contrast report (generated)",
        "",
        "Generated by `tools/build.py` from `tokens/checks.json`; do not edit. Every row is a build gate:",
        "the build fails if any theme drops below the minimum. Values are WCAG 2.x ratios.",
        "",
        "| Foreground | Background | Min | Why | " + " | ".join(themes) + " |",
        "|---|---|---|---|" + "---|" * len(themes),
    ]
    for c in checks:
        cells = []
        for th in themes:
            if c.get("themes") and th not in c["themes"]:
                cells.append("–")
                continue
            toks = ctx.themes[th]
            fg, bg = toks[c["fg"]], toks[c["bg"]]
            r = colour.contrast(colour.dtcg_to_rgba(fg.value), colour.dtcg_to_rgba(bg.value))
            cells.append(f"{r:.2f} <sub>`{_hex(fg)}`/`{_hex(bg)}`</sub>")
        lines.append(f"| `{c['fg']}` | `{c['bg']}` | {c['min']} | {c.get('why', '')} | " + " | ".join(cells) + " |")
    lines += ["", "Deliberately unchecked: `text.disabled` and `border.subtle` (inactive/decorative), and "
              "`text.secondary` on `surface.face-hover` (hovered items brighten text to primary)."]
    f = ROOT / "foundations/contrast.generated.md"
    f.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return [f]
